import { randomBytes } from 'node:crypto';
import { mkdir, rename, rm, writeFile } from 'node:fs/promises';
import { posix } from 'node:path';
import type { ProjectMatch, RoomDTO } from '@luady/shared';

/**
 * memory/ROOMS.auto.md: the rooms as the manager reads them, rewritten after every change (like PROJECTS.auto.md).
 * The `rooms_list` tool answers with the same lines.
 */

const KIND_WORDS: Readonly<Record<RoomDTO['kind'], string>> = { server: 'server room', project: 'project room', local: 'this computer' };

const matchText = (m: ProjectMatch): string => `${m.by} ${m.glob}`;

/** One room in one line: id, name, kind, host, matches, position. */
export function roomLine(room: RoomDTO): string {
  const host = room.host === null ? 'any host' : `host ${room.host}${room.hostState === 'removed' ? ' (removed)' : ''}`;
  const matches = room.match.length === 0 ? 'everything on its host' : room.match.map(matchText).join(', ');
  return `- **${room.name}** (\`${room.id}\`) · ${KIND_WORDS[room.kind]} · ${host} · ${matches} · slot ${room.position}`;
}

/** The whole list, by position; with no rooms, says so. */
export function roomsText(rooms: readonly RoomDTO[]): string {
  if (rooms.length === 0) return 'No rooms yet. The owner adds them on the website.';
  return [...rooms].sort((a, b) => a.position - b.position).map(roomLine).join('\n');
}

export function renderRoomsAuto(rooms: readonly RoomDTO[], nowIso: string): string {
  return [
    '# Rooms (generated by the hub after every change; do not edit)',
    `Updated ${nowIso.slice(0, 16).replace('T', ' ')} UTC. A room is a place on the map: a server's room, a project room`
      + ' (sessions whose project or folder matches), or this computer. A session sits in the most specific room that matches it.',
    '',
    roomsText(rooms),
    '',
  ].join('\n');
}

/** Atomic write (a temp file of its own, then rename), so the manager never reads a half-written file. */
export async function writeRoomsAuto(brainDir: string, rooms: readonly RoomDTO[], nowIso: string): Promise<void> {
  const dir = posix.join(brainDir, 'memory');
  const target = posix.join(dir, 'ROOMS.auto.md');
  const temp = `${target}.${randomBytes(6).toString('hex')}.tmp`;
  await mkdir(dir, { recursive: true });
  try {
    await writeFile(temp, renderRoomsAuto(rooms, nowIso), { mode: 0o640 });
    await rename(temp, target);
  } catch (err) {
    await rm(temp, { force: true }).catch(() => undefined);
    throw err;
  }
}
